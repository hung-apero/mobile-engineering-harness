const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const S = require('../../vendor/learn-app/lib/learn-app-state.cjs');
const store = require('../../src/specs/store.cjs');
const { setupBuild, g, VERSION, SERIAL } = require('./specs-build-fixtures.cjs');

test('an approved spec stays approved until dz spec build, then runs to the version branch in dry run', async t => {
  const s = setupBuild(t);
  await s.toApproved();
  await s.tick();
  assert.equal(s.spec().state, 'approved');
  assert.match((await s.cmd('build', String(s.id), '--version', VERSION)).join('\n'), /chạy khô/);
  await s.until(() => s.running('spec').length === 1);
  const { env, args } = s.calls.at(-1);
  assert.deepEqual([env.LEARN_APP_PARALLEL, env.LEARN_APP_HEADLESS, env.LEARN_APP_TRACKING], ['2', '1', 'off']);
  assert.match(args.at(-1), /đoạn build\./);
  assert.ok(args.includes('Bash(adb:*)') && args.includes('Bash(git push:*)'));
  assert.equal(fs.readFileSync(path.join(s.repo(), 'local.properties'), 'utf8'), 'sdk.dir=/x\n');
  assert.equal(JSON.parse(fs.readFileSync(path.join(s.repo(), '.learn-app/inputs/headless.json'))).segment, 'build');
  await s.code();
  assert.equal(s.spec().state, 'smoking');
  await s.until(() => s.running('spec').length === 1);
  const smoke = s.calls.at(-1);
  assert.equal(smoke.env.ANDROID_SERIAL, SERIAL);
  assert.ok(!smoke.args.includes('Bash(adb:*)') && smoke.args.includes('Bash(emulator:*)'));
  assert.match(smoke.args.at(-1), new RegExp(`Thiết bị duy nhất là ${SERIAL}`));
  assert.equal(s.devices.held.get(SERIAL), `spec:${s.id}:run`);
  await s.smoke();
  assert.equal(s.devices.held.size, 0);
  await s.review();
  await s.gate();
  await s.build();
  await s.state('po-trial');
  const { candidate, trial } = s.spec().data.build;
  assert.equal(trial.sha, candidate.sha);
  assert.deepEqual(s.tree(candidate.sha), ['.gitignore', 'app.txt', 'feature.txt']);
  assert.equal(g(s.mirror, 'rev-list', '--count', `${candidate.start}..${candidate.sha}`), '1');
  assert.ok(s.would().some(text => /gh pr create --draft dz\/feature-ABC1-1 -> main/.test(text)));
  assert.ok(s.would().some(text => text === `git push ${candidate.sha}:refs/heads/dz/feature-ABC1-1 (apero/learn-app)`));
  assert.ok(s.would().includes(`firebase distribute ${candidate.sha}`));
  assert.equal(g(s.github, 'for-each-ref', '--format=%(refname)'), 'refs/heads/main');
  assert.match(s.waits().find(wait => wait.role === 'po').link, /\/review\//);

  assert.deepEqual(await s.approveTrial(trial.sha), { ok: true });
  assert.equal(S.readState(s.repo()).gates.g3.status, 'approved');
  await s.gate();
  await s.build();
  await s.state('landed-dry');
  const [batch] = s.batches();
  assert.deepEqual([batch.state, batch.data.delivered, batch.data.spec.sha], ['done', true, candidate.sha]);
  const tip = g(s.mirror, 'rev-parse', `refs/heads/dz/release-${VERSION}`);
  assert.deepEqual(s.tree(tip), ['.gitignore', 'app.txt', 'feature.txt']);
  assert.equal(g(s.mirror, 'log', '--all-match', '--format=%H', tip, '--', '.learn-app'), '');
  assert.ok(s.would().some(text => /gh pr create --draft dz\/release-1\.9\.2 -> main/.test(text)));
  assert.equal(g(s.github, 'for-each-ref', '--format=%(refname)'), 'refs/heads/main');
  assert.deepEqual(s.waits().filter(wait => wait.role !== 'dev').map(wait => wait.role), ['qa']);
  assert.ok(s.ghCalls.length === 0);
});

test('the PO approval of an older candidate does not count for a newer one', async t => {
  const s = setupBuild(t);
  await s.toBuilding();
  const first = await s.toTrial();
  assert.equal((await s.facade.feedback(s.id, { text: 'Nút sai màu ở màn path' }, 'po', s.now)).ok, true);
  assert.equal(s.spec().state, 'building');
  assert.equal(S.readState(s.repo()).step, 'coding');
  await assert.rejects(s.approveTrial(first), { code: 'STATE' });
  await s.code({ files: { 'feature.txt': 'feature 2\n' } });
  await s.smoke();
  await s.review();
  await s.gate();
  await s.build();
  await s.state('po-trial');
  const { trial, candidate } = s.spec().data.build;
  assert.notEqual(trial.sha, first);
  assert.equal(candidate.n, 2);
  assert.equal(g(s.mirror, 'rev-parse', `${trial.sha}^`), first);
  await assert.rejects(s.approveTrial(first), { code: 'STALE' });
  store.patchData(s.ctx.db, s.id, { build: { ...s.spec().data.build, trial: { ...trial, approved: { sha: first, quote: 'x', by: 'po', at: 1 } } } }, s.now);
  await s.tick();
  assert.equal(s.spec().state, 'po-trial');
  assert.equal(s.batches().length, 0);
  assert.deepEqual(await s.approveTrial(trial.sha), { ok: true });
  assert.equal(s.spec().state, 'landing');
});

test('a commit that is not the approved one is never landed', async t => {
  const s = setupBuild(t);
  await s.toBuilding();
  const sha = await s.toTrial();
  await s.approveTrial(sha);
  g(s.mirror, 'update-ref', 'refs/heads/fix/spec-1-1', g(s.mirror, 'rev-parse', 'refs/heads/main'));
  await s.state('parked');
  assert.match(s.spec().data.parked.reason, /không gộp được vào bản/);
  assert.equal(g(s.mirror, 'rev-parse', `refs/heads/dz/release-${VERSION}`), g(s.mirror, 'rev-parse', 'refs/heads/main'));
});
